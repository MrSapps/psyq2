/* GTE macros in the PSY-Q inline_c.h style, one asm statement per instruction (see calib/misc.c) */
#define gte_mvr(reg, r0) __asm__ volatile("move $" #reg ",%0" : : "r"(r0) : "$" #reg, "memory")
#define gte_op(s) __asm__ volatile(s)
#define gte_st(s) __asm__ volatile(s : : : "memory")
#define gte_ldv0(r0) { gte_mvr(12, r0); gte_op("lwc2 $0,0($12)"); gte_op("lwc2 $1,4($12)"); }
#define gte_ldv3c(r0) { gte_mvr(12, r0); \
    gte_op("lwc2 $0,0($12)"); gte_op("lwc2 $1,4($12)"); gte_op("lwc2 $2,8($12)"); \
    gte_op("lwc2 $3,12($12)"); gte_op("lwc2 $4,16($12)"); gte_op("lwc2 $5,20($12)"); }
#define gte_rtv0() { gte_op("nop"); gte_op("nop"); gte_op(".word 0x4A486012"); }
#define gte_rtpt() { gte_op("nop"); gte_op("nop"); gte_op(".word 0x4A280030"); }
#define gte_stsxy3c(r0) { gte_mvr(12, r0); \
    gte_st("swc2 $12,0($12)"); gte_st("swc2 $13,4($12)"); gte_st("swc2 $14,8($12)"); }
#define gte_stsz(r0) { gte_mvr(12, r0); gte_st("swc2 $19,0($12)"); }
/* t7 is never allocated in ProcessMissiles_Many: some GTE macro of the original clobbered $15 too */
#define gte_mvlvtr() __asm__ volatile("mfc2 $12,$25\nmfc2 $13,$26\nmfc2 $14,$27\nctc2 $12,$5\nctc2 $13,$6\nctc2 $14,$7" : : : "$12", "$13", "$14", "$15")

