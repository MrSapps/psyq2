struct MISSILE *FindFreeMissile(void)
{
    struct MISSILE *Missile;

    for (Missile = Missiles; Missile < &Missiles[64]; Missile++) {
        if (!Missile->Life) {
            memset(Missile, 0, sizeof(struct MISSILE));
            return Missile;
        }
    }
    return 0;
}

void FreeMissile(struct MISSILE *Missile)
{
    Missile->Life = 0;
}

void InitialiseMissiles(void)
{
    struct MISSILE *Missile;

    for (Missile = Missiles; Missile < &Missiles[64]; Missile++)
        Missile->Life = 0;
}

void ProcessMissiles_Many(void)
{
    static struct SIMPOL ModelData[8] = {
    {{0, 1, 2, 3}, {{0xff, 0x40, 0x0, 0x38}, {0xff, 0x40, 0x0, 0x38}, {0xff, 0xff, 0x0, 0x38}, {0xff, 0xff, 0x0, 0x38}}},
    {{0, 4, 1, 5}, {{0xff, 0x40, 0x0, 0x38}, {0xff, 0x40, 0x0, 0x38}, {0xff, 0x40, 0x0, 0x38}, {0xff, 0x40, 0x0, 0x38}}},
    {{1, 5, 3, 7}, {{0xff, 0x40, 0x0, 0x38}, {0xff, 0x40, 0x0, 0x38}, {0xff, 0xff, 0x0, 0x38}, {0xff, 0xff, 0x0, 0x38}}},
    {{3, 7, 2, 6}, {{0xff, 0xff, 0x0, 0x38}, {0xff, 0xff, 0x0, 0x38}, {0xff, 0xff, 0x0, 0x38}, {0xff, 0xff, 0x0, 0x38}}},
    {{2, 6, 0, 4}, {{0xff, 0xff, 0x0, 0x38}, {0xff, 0xff, 0x0, 0x38}, {0xff, 0x40, 0x0, 0x38}, {0xff, 0x40, 0x0, 0x38}}},
    {{5, 4, 7, 6}, {{0xff, 0x40, 0x0, 0x38}, {0xff, 0x40, 0x0, 0x38}, {0xff, 0xff, 0x0, 0x38}, {0xff, 0xff, 0x0, 0x38}}},
    {{0, 0, 0, 0}, {{0x0, 0x0, 0x0, 0x0}, {0x0, 0x0, 0x0, 0x0}, {0x0, 0x0, 0x0, 0x0}, {0x0, 0x0, 0x0, 0x0}}},
    {{0, 0, 0, 0}, {{0x0, 0x0, 0x0, 0x0}, {0x0, 0x0, 0x0, 0x0}, {0x0, 0x0, 0x0, 0x0}, {0x0, 0x0, 0x0, 0x0}}},
    };
    struct SCRPNT ScrPnts[8];
    struct MISSILE *Missile;
    struct VECT Stop;
    struct VECT PartLoc;
    struct VECT Intersect;
    struct VECT Tran;
    struct CREATURE *Target;
    struct SVECT ToMove;
    struct SVECT Vel[15];
    struct SVECT Off[15];
    struct SVECT BaseVel;
    struct SVECT Offset;
    struct SVECT Rel;
    struct SVECT BullVel;
    int a;
    int b;
    int Win;
    int Za;
    int CurrentArea;
    struct POLY_G4 *OldPoly;

    Za = 0;
    CurrentArea = -1;
    SetRotMatrix(&GameWindows[0].CamMat);
    SetGeomOffset(GameWindows[0].Geom.sx, GameWindows[0].Geom.sy);
    SetGeomScreen(GameWindows[0].Focal);
    CurrScreenSize = GameWindows[0].Size;

    for (Missile = Missiles; Missile < &Missiles[64]; Missile++) {
        if (!Missile->Life)
            continue;
        Missile->Life -= NewVcounts;
        if (Missile->Life <= 0) {
            FreeMissile(Missile);
            continue;
        }
        ToMove.vx = Missile->Col3dMove.Vel.vx * NewVcounts;
        ToMove.vy = Missile->Col3dMove.Vel.vy * NewVcounts;
        ToMove.vz = Missile->Col3dMove.Vel.vz * NewVcounts;

        Stop.vx = Missile->Location.vx + ToMove.vx;
        Stop.vy = Missile->Location.vy + ToMove.vy;
        Stop.vz = Missile->Location.vz + ToMove.vz;

        Target = LineIntersectCreCylinder(&Missile->Location, &Stop, Missile->Instigator, &Stop, ThisBumpList, ThisBumpListEnd);

        if (!VisableSolidBoxLine(&Missile->Location, &Stop, &Stop)) {
            Target = 0;
            if (CollisionReturnData.IdentType == 2) {
                /* written as SolidBoxs + n, not &SolidBoxs[n]: the array form CSEs the base differently */
                if ((SolidBoxs + CollisionReturnData.Ident)->Flags & 4) {
                    (SolidBoxs + CollisionReturnData.Ident)->Flags |= 8;
                    DoSolidBoxEventDamage(SolidBoxs + CollisionReturnData.Ident, Missile->Damage, &Stop);
                }
                dprintf(&GameWindows[0], "MissileHit a solid box\n");
                FreeMissile(Missile);
                if (Missile->Flags & 8)
                    goto Glint;
            }
        }
        if (Target) {
            if (Target->Player) {
                if (Target->Player->Window)
                    GenMissileHitPlane(&Target->Player->Window->CamPos, &Target->Player->Window->ScreenPlane, &Stop, &Missile->Col3dMove.Vel);
            } else
                LineIntersectCrePlane(&Missile->Location, &Stop, Target, &Stop);
            Missile->Location = Stop;
            DoDamage(Missile->Instigator, Target, Missile->Damage, Missile->DamageType, &Missile->Location);
            FreeMissile(Missile);
            if (Missile->Flags & 8)
                goto Glint;
        }
        Missile->Location = Stop;

        if (Missile->Flags & 4) {
            for (Win = 0; Win < MaxWindows; Win++) {
                if (!AreaValid(Win, Missile->Col3dMove.Area))
                    continue;
                if (MaxWindows == 1) {
                    if (Missile->Col3dMove.Area != CurrentArea) {
                        CurrentArea = Missile->Col3dMove.Area;
                        SetupScreenGivenArea(Win, CurrentArea);
                    }
                } else {
                    SetupScreenGivenArea(Win, Missile->Col3dMove.Area);
                    SetRotMatrix(&GameWindows[Win].CamMat);
                    CurrCamPos = &GameWindows[Win].CamPos;
                }
                if (NextGeneralG4 > LastGeneralG4 - 6)
                    continue;
                Rel.vx = Missile->Location.vx - CurrCamPos->vx;
                Rel.vy = Missile->Location.vy - CurrCamPos->vy;
                Rel.vz = Missile->Location.vz - CurrCamPos->vz;

                gte_ldv0(&Rel); gte_rtv0(); gte_mvlvtr();
                gte_ldv3c(&Missile->P0); gte_rtpt(); gte_stsxy3c(&ScrPnts[0]);
                gte_ldv3c(&Missile->P3); gte_rtpt(); gte_stsxy3c(&ScrPnts[3]);
                gte_ldv3c(&Missile->P5); gte_rtpt(); gte_stsxy3c(&ScrPnts[5]);
                gte_stsz(&Za);

                NextGeneralG4 = HH_SimpleModel_(ModelData, &ModelData[5], ScrPnts, OldPoly = NextGeneralG4);
                GeneralG4Sort(OldPoly, &Missile->Location, (struct SHORTPAIR){Missile->Col3dMove.Area, Win}, Za);
            }
        }

        if (Missile->Flags & 2)
            AddLight(&Missile->Location, *&(struct COLOUR){0xff, 0x64, 0x4b, 0}, *&(struct POWER){300, 800}, *&(struct SHORTPAIR){0, 0});

        if (Missile->Flags & 0x10)
            AddLight(&Missile->Location, *&(struct COLOUR){0xff, 0x64, 0x4b, 0}, *&(struct POWER){800, 1600}, *&(struct SHORTPAIR){0, 0});

        if (Missile->Flags & 1) {
            if (++Missile->TrailTime > Missile->Trail)
                Missile->TrailTime = Missile->Trail;

            Intersect = Missile->Location;

            for (b = 0; b < Missile->TrailTime; b++) {
                Offset.vx = ToMove.vx >> 1;
                Offset.vy = ToMove.vy >> 1;
                Offset.vz = ToMove.vz >> 1;

                PartLoc.vx = Intersect.vx - Offset.vx;
                PartLoc.vy = Intersect.vy - Offset.vy;
                PartLoc.vz = Intersect.vz - Offset.vz;

                BaseVel.vx = ToMove.vx >> 4;
                BaseVel.vy = ToMove.vy >> 4;
                BaseVel.vz = ToMove.vz >> 4;

                Rel.vx = (ToMove.vx << 4) / Missile->TrailDensity;
                Rel.vy = (ToMove.vy << 4) / Missile->TrailDensity;
                Rel.vz = (ToMove.vz << 4) / Missile->TrailDensity;

                Off[0] = (struct SVECT){-Offset.vx, -Offset.vy, -Offset.vz};
                Vel[0] = BaseVel;
                for (a = 1; a < Missile->TrailDensity; a++) {
                    Off[a].vx = Off[a - 1].vx + Rel.vx;
                    Off[a].vy = Off[a - 1].vy + Rel.vy;
                    Off[a].vz = Off[a - 1].vz + Rel.vz;
                    Vel[a].vx = BaseVel.vx + ((rand() - 0x4000) >> 12);
                    Vel[a].vy = BaseVel.vy + ((rand() - 0x4000) >> 12);
                    Vel[a].vz = BaseVel.vz + ((rand() - 0x4000) >> 12);
                }
                AddParticlesSL0(&PartLoc, Off, Vel, &ParticleColours_Yellow, &ParticleColours_Yellow, Missile->TrailDensity, 23, 0x2000, Missile->Col3dMove.Area);

                Intersect.vx += Missile->Col3dMove.Vel.vx * 2;
                Intersect.vy += Missile->Col3dMove.Vel.vy * 2;
                Intersect.vz += Missile->Col3dMove.Vel.vz * 2;
            }
        }

        if (ProcessCol3dMove(&CollMap, &Missile->Col3dMove, &Missile->Location, NewVcounts))
            continue;
        FreeMissile(Missile);
Glint:
        if (Target) {
            DoNoise(Missile->Instigator, &Missile->Location, 2);
            if (Missile->Flags & 8)
                GenerateBulletBlood(&Missile->Location, Missile->Col3dMove.Area);
        } else {
            DoNoise(Missile->Instigator, &Missile->Location, 2);
            if (Missile->Flags & 8) {
                for (b = 0; b < 2; b++) {
                    for (a = 0; a < 15; a++) {
                        Vel[a].vx = (rand() - 0x4000) >> 9;
                        Vel[a].vy = (rand() - 0x4000) >> 9;
                        Vel[a].vz = (rand() - 0x4000) >> 9;
                    }
                    AddParticlesSL(&Missile->Location, Vel, &ParticleColours_Yellow, &ParticleColours_Yellow, 15, 15, 0x2000, Missile->Col3dMove.Area);
                }
            }
        }
    }
}

void ProcessMissiles(void)
{
    ProcessMissiles_Many();
}

/* Space is int in the SYM, but the code loads it as a short at entry */
void AnyoneFireInstantBullet(struct CREATURE *Cre, struct VECT *Start, struct SVECT *Dir, int Damage, short Space, int BulletType)
{
    struct CREATURE *Target;
    struct VECT Stop;
    struct VECT Stop2;
    struct SVECT Rel;
    short StopArea;
    short hitsolid;

    hitsolid = 0;
    Rel = *Dir;
    Stop.vx = Start->vx + Rel.vx;
    Stop.vy = Start->vy + Rel.vy;
    Stop.vz = Start->vz + Rel.vz;
    if (!VisableSolidBoxLine(Start, &Stop, &Stop2) && CollisionReturnData.IdentType == 2) {
        hitsolid = 1;
        Stop = Stop2;
    }
    Visable3d(&CollMap, Start, &Stop, Space);
    Stop = CollMap.AreaIntersectLast->Intersect;
    StopArea = CollMap.ReturnSpace->Area;
    if (hitsolid && Stop.vx == Stop2.vx && Stop.vy == Stop2.vy && Stop.vz == Stop2.vz
        && (SolidBoxs[CollisionReturnData.Ident].Flags & 4)) {
        SolidBoxs[CollisionReturnData.Ident].Flags |= 8;
        DoSolidBoxEventDamage(&SolidBoxs[CollisionReturnData.Ident], Damage, &Stop);
        dprintf(&GameWindows[0], "Hit a solid box\n");
    }
    Target = LineIntersectCreCylinder(Start, &Stop, Cre, &Stop, ThisBumpList, ThisBumpListEnd);
    if (Target) {
        if (Target->Player && Target->Player->Window)
            GenMissileHitPlane(&Target->Player->Window->CamPos, &Target->Player->Window->ScreenPlane, &Stop, &Rel);
        StopArea = Target->Box.Area;
        DoDamage(Cre, Target, Damage, 0x12, &Stop);
        GenerateBulletBlood(&Stop, StopArea);
    } else
        GenerateBulletGfx(&Stop, StopArea);
    if (Cre->Player)
        DoNoise(Cre, &Stop, 2);
}

void GenerateBulletGfx(struct VECT *Location, int Area)
{
    struct POWER Power;
    struct SVECT Vel[15];
    struct SVECT Off[15];
    int a;

    for (a = 0; a < 15; a++) {
        Off[a].vx = (rand() - 0x4000) >> 7;
        Off[a].vy = (rand() - 0x4000) >> 7;
        Off[a].vz = (rand() - 0x4000) >> 7;
        Vel[a].vx = (rand() - 0x4000) >> 11;
        Vel[a].vy = (rand() - 0x4000) >> 11;
        Vel[a].vz = (rand() - 0x4000) >> 11;
    }
    AddParticlesSL0(Location, Off, Vel, &ParticleColours_Grey, &ParticleColours_SolidGrey, 15, 32, 0x1000, Area);
}

void GenerateBulletBlood(struct VECT *Location, int Area)
{
    int a;
    int b;
    struct SVECT Vel[15];
    struct PARTICLE *Particle;

    for (b = 0; b < 2; b++) {
        for (a = 0; a < 15; a++) {
            Vel[a].vx = (rand() - 0x4000) >> 10;
            Vel[a].vy = (rand() - 0x4000) >> 10;
            Vel[a].vz = (rand() - 0x4000) >> 10;
        }
        Particle = AddParticlesSL(Location, Vel, &ParticleColours_BloodRed, &ParticleColours_DarkBloodRed, 15, 15, 0x1800, Area);
        if (Particle)
            Particle->Drift.vy = 2;
    }
}
