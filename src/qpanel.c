void Draw_Panel(struct WINDOW *GameWin, struct SPRITEDATA *PanelData, struct SHORTPAIR ItemsType, int WeaponIcons)
{
    struct PLAYER *Player;
    struct SPRITEDATA *Panel;
    struct UVWH Weapon_GT4;
    struct RECT Weapon_Pos;
    long *Ot;
    short Count;
    short MaxPanelItems;
    short GameType;

    MaxPanelItems = ItemsType.a;
    Panel = PanelData;
    GameType = (ItemsType.b - 1) << 2;
    Player = &Players[GameWin - GameWindows];
    Ot = (long *)&currdb->Ot[GameWin - GameWindows][49];
    for (Count = 0; Count++ < MaxPanelItems; Panel++) {
        if (Panel->w != 1 && Panel->h != 1) {
            if (MenuPoly >= LastMenuPoly)
                break;
            setPolyFT4(MenuPoly);
            setUVWH(MenuPoly, Panel->u, Panel->v, Panel->w, Panel->h);
            setXYWH(MenuPoly, Panel->x, Panel->y, Panel->w, Panel->h);
            setRGB0(MenuPoly, 0xc0, 0xc0, 0xc0);
            MenuPoly->tpage = alltpages[Panel->tp];
            MenuPoly->clut = palette[Panel->pal];
            AddPrim_(Ot, MenuPoly++);
        }
    }
    if (WeaponIcons) {
        if (Player->Extras.Previous_WeaponSelected && Player->Extras.Previous_WeaponSelected != Player->Extras.Next_WeaponSelected) {
            short PosOff = Player->Extras.Previous_WeaponSelected * 5;
            Weapon_GT4.u = QuakeIconTable[PosOff];
            Weapon_GT4.v = QuakeIconTable[PosOff + 1];
            Weapon_GT4.w = QuakeIconTable[PosOff + 2];
            Weapon_GT4.h = QuakeIconTable[PosOff + 3];
            Weapon_Pos.x = QPanel_PrevNext[GameType];
            Weapon_Pos.y = QPanel_PrevNext[GameType + 1];
            Weapon_Pos.w = Weapon_GT4.w;
            Weapon_Pos.h = Weapon_GT4.h;
            FadePolyGT4(&Weapon_GT4, &Weapon_Pos, Ot, (struct SHORTPAIR){ QuakeIconTable[PosOff + 4], 1 });
        }
        if (Player->Extras.Next_WeaponSelected) {
            short PosOff = Player->Extras.Next_WeaponSelected * 5;
            Weapon_GT4.u = QuakeIconTable[PosOff];
            Weapon_GT4.v = QuakeIconTable[PosOff + 1];
            Weapon_GT4.w = QuakeIconTable[PosOff + 2];
            Weapon_GT4.h = QuakeIconTable[PosOff + 3];
            Weapon_Pos.x = QPanel_PrevNext[GameType + 2];
            Weapon_Pos.y = QPanel_PrevNext[GameType + 3];
            Weapon_Pos.w = Weapon_GT4.w;
            Weapon_Pos.h = Weapon_GT4.h;
            FadePolyGT4(&Weapon_GT4, &Weapon_Pos, Ot, (struct SHORTPAIR){ QuakeIconTable[PosOff + 4], 0 });
        }
    }
}

