void InitialiseMenuEveryFrame(void)
{
    MenuPoly = (struct POLY_FT4 *)((char *)currdb + 0x3984);
    FMenuPoly = (struct POLY_GT4 *)((char *)currdb + 0x4014);
    LastMenuPoly = (struct POLY_FT4 *)((char *)currdb + 0x4014);
    LastFMenuPoly = (struct POLY_GT4 *)((char *)currdb + 0x41b4);
}

void FadePolyGT4(struct UVWH *GraphicUVWH, struct RECT *Pos, long *Ot, struct SHORTPAIR PalFlip)
{
    int PaletteIdent;
    int Flip;

    PaletteIdent = PalFlip.a;
    Flip = PalFlip.b;
    if (FMenuPoly < LastFMenuPoly - 1) {
        setPolyGT4(FMenuPoly);
        setUVWH(FMenuPoly, GraphicUVWH->u, GraphicUVWH->v, GraphicUVWH->w, GraphicUVWH->h);
        setXYWH(FMenuPoly, Pos->x, Pos->y, Pos->w, Pos->h);
        if (Flip) {
            setRGB0(FMenuPoly, 0, 0, 0);
            setRGB2(FMenuPoly, 0, 0, 0);
            setRGB1(FMenuPoly, 0x80, 0x80, 0x80);
            setRGB3(FMenuPoly, 0x80, 0x80, 0x80);
        } else {
            setRGB0(FMenuPoly, 0x80, 0x80, 0x80);
            setRGB2(FMenuPoly, 0x80, 0x80, 0x80);
            setRGB1(FMenuPoly, 0, 0, 0);
            setRGB3(FMenuPoly, 0, 0, 0);
        }
        FMenuPoly->tpage = alltpages[14] | 0x20;
        FMenuPoly->clut = palette[PaletteIdent];
        AddPrim_(Ot, FMenuPoly++);
        SetSemiTrans(FMenuPoly - 1, 1);
        *FMenuPoly = *(FMenuPoly - 1);
        if (Flip) {
            setRGB1(FMenuPoly, 0x3e, 0x3e, 0x3e);
            setRGB3(FMenuPoly, 0x3e, 0x3e, 0x3e);
        } else {
            setRGB0(FMenuPoly, 0x3e, 0x3e, 0x3e);
            setRGB2(FMenuPoly, 0x3e, 0x3e, 0x3e);
        }
        FMenuPoly->tpage = alltpages[14] | 0x40;
        FMenuPoly->clut = palette[73];
        AddPrim_(Ot, FMenuPoly++);
    }
}

