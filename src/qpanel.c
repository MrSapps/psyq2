    HunOff = BCDNo[0] << 2;
    TenOff = BCDNo[1] << 2;
    OneOff = BCDNo[2] << 2;
    Hundred->u = QuakeGunNumbers[HunOff];
    Hundred->v = QuakeGunNumbers[HunOff + 1];
    Ten->u = QuakeGunNumbers[TenOff];
    Ten->v = QuakeGunNumbers[TenOff + 1];
