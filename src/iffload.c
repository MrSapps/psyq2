int MyGetCDStatus(void)
{
    unsigned char result[8];
    CdControlB(1, 0, result);
    if (result[0] & 0x10)
        return 0;
    if (result[0] & 2)
        return 2;
    return 1;
}

void ReReadToc(void)
{
    unsigned char result[8];
    unsigned char com;
    struct CdlLOC pos;
    CdControlB(0xe, &com, result);
    while (MyGetCDStatus() != 2)
        ;
    while (!CdControlB(0x13, 0, result))
        ;
    com = 0x80;
    CdControlB(0xe, &com, result);
    VSync(3);
    GetToc();
}

