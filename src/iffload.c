static void PcReadAll(int h, char *dest, int len)
{
    int pos;
    int lr;

    lr = -1;
    pos = PClseek(h, 0, 1);
    while (lr != len) {
        PClseek(h, pos, 0);
        lr = PCread(h, dest, len);
    }
}

static void PcLoad(char *buffer, char *name)
{
    int h;
    int len;

    h = MYPCopen(name);
    len = MYPClseek(h, 0, 2);
    MYPClseek(h, 0, 0);
    PcReadAll(h, buffer, len);
    MYPCclose(h);
}

static void LoadToBuffer(char *Name, char *Buffer)
{
    if (UseCdData)
        CdLoad(Buffer, Name);
    else
        PcLoad(Buffer, Name);
}

char *LoadIffToRam_ConCat_NewMode(char *loadname, struct HEADERTYPE *Header, short *PSXColours)
{
    char *p2;
    int found;
    int b;
    int numpics;
    int numtppics;
    int nummappals;
    int nummodpals;
    char *names;
    char *names2;
    char *pic;
    short *pal;
    int numbytes;
    char *buf;

    if (AllIffPics) {
        numtppics = ((unsigned char *)AllIffPics)[0];
        numpics = ((unsigned char *)AllIffPics)[1];
        nummappals = ((unsigned char *)AllIffPics)[2];
        nummodpals = ((unsigned char *)AllIffPics)[3];
        names = (char *)(AllIffPics + 1);
        names += (numpics + numtppics) * 8;
        Global16colourpals = (short *)names;
        names += (nummappals + nummodpals) * 32;
        NumMapPals = nummappals;
        NumModelPals = nummodpals;
        found = -1;
        names2 = names + numpics * 512;
        for (b = 0; b < numpics + numtppics; b++) {
            if (!strcmp(names2, loadname)) {
                found = b;
                break;
            }
            names2 += strlen(names2);
            names2++;
        }
        if (found >= 0) {
            if (found >= numtppics) {
                pal = (short *)(AllIffPics + 1);
                pal += found * 4;
                Header->Width = pal[2];
                Header->Height = pal[3];
                numbytes = pal[2] * pal[3];
            } else {
                Header->Width = 0x80;
                Header->Height = 0x100;
                numbytes = 0x8000;
            }
            pic = (char *)AllIffPics;
            pic += ((int *)pic)[found * 2 + 1];
            p2 = MY_malloc_name(Header->Width * Header->Height, loadname);
            if (p2)
                UnpackByteRun(numbytes, pic, p2);
            return p2;
        }
    }
    return 0;
}

