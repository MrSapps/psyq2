{
    return PClseek(h, 0, 0);
}

static int PcClose(int h)
{
    return PCclose(h);
}

static int PcFileLen(char *name)
{
    int h;
    char name2[100];
    int len;

    strcpy(name2, name);
    h = PCopen(name2, 0, 0);
    if (h >= 0) {
        len = PcSeekEnd(h);
        PcSeekStart(h);
        PcClose(h);
        return len;
    }
    return 0;
}

static int FileLen(char *Name)
{
    if (UseCdData)
        return CdFileLen(Name);
    return PcFileLen(Name);
}

