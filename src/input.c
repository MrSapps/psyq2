static int AnlgConv(int InVal)
{
    InVal -= 128;
    if (abs(InVal) < 40)
        return 0;
    if (InVal < 0)
        InVal = (((InVal + 40) << 7) + 44) / 88;
    else
        InVal = (((InVal - 40) << 7) + 44) / 88;
    return (InVal * InVal * InVal) >> 14;
}

