static char *itoa(int num)
{
    int a;
    int mflag;
    char *p;

    p = &itoabuf[19];
    mflag = 0;
    *p-- = 0;
    if (num < 0)
    {
        num = -num;
        mflag = 1;
    }
    if (num == 0)
        *p-- = '0';
    else
        while (num > 0)
        {
            a = num / 10;
            *p-- = num - a * 10 + '0';
            num = a;
        }
    if (mflag)
        *p-- = '-';
    return p + 1;
}

