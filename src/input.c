void SwapButtons(int Win)
{
    struct CTRLER *Input;
    int Manual;
    int TakeOver;
    int Dead;

    TakeOver = 0;
    Dead = 0;
    Input = &GameWindows[Win].Input;
    if (GameRunningMode == 3)
        Input->Padd = Input->Original = 0;
    switch (Input->SelfPlayMode)
    {
    case 0:
        Input->OPadd = Input->Padd;
        Input->Padd = Input->Original;
        if (Input->Method == 5 || Input->Method == 7 || Input->Method == 10)
        {
            *(int *)&Input->OAPaddLX = *(int *)&Input->APaddLX;
            if (Input->Method != 10)
            {
                Input->APaddLX = AnlgConv((unsigned char)(Input->AnlgOriginal >> 24));
                Input->APaddLY = AnlgConv((unsigned char)(Input->AnlgOriginal >> 16));
            }
            Input->APaddRX = AnlgConv((unsigned char)(Input->AnlgOriginal >> 8));
            Input->APaddRY = AnlgConv((unsigned char)Input->AnlgOriginal);
        }
        if (Input->Method == 9 || Input->Method == 10)
        {
            Input->APaddLX = (int)Input->AnlgOriginal >> 24;
            Input->APaddLY = (int)Input->AnlgOriginal >> 16;
            Input->APaddRX = Input->APaddRY = 0;
        }
        break;
    case 1:
        Input->Method = 4;
        SetController(Win, 6);
        Input->OPadd = Input->Padd;
        if (!TakeOver)
        {
            if (*Input->SelfPlayPntr != -1)
            {
                Input->Padd = *Input->SelfPlayPntr & 0xfff0;
                if (Win == 0)
                {
                    NewVcounts = 0;
                    if (*Input->SelfPlayPntr & 8)
                        NewVcounts = PalNtscRate;
                    if (*Input->SelfPlayPntr & 1)
                        NewVcounts += PalNtscRate * 2;
                    if (*Input->SelfPlayPntr & 2)
                        NewVcounts += PalNtscRate * 4;
                    if (*Input->SelfPlayPntr & 4)
                        NewVcounts += PalNtscRate * 8;
                }
                Input->SelfPlayPntr++;
            }
            else
            {
                Input->Padd = -1;
                Input->SelfPlayMode = 3;
                NoInputTime = 0;
            }
        }
        Manual = Input->Original;
        if (!LevelIsMultiPlayer && GameWindows[Win].Creature
            && ((struct CREATURE *)GameWindows[Win].Creature)->Health <= 0)
            Dead = 1;
        if (Input->Padd == -1 || Manual || Dead)
        {
            Input->Padd = 0;
            NoInputTime = 0;
            InSelfPlayMode = 0;
            Input->SelfPlayMode = 3;
        }
        break;
    case 2:
        Input->Method = 4;
        SetController(Win, 6);
        Input->OPadd = Input->Padd;
        if (Input->SelfPlayEndPntr == Input->SelfPlayPntr)
        {
            if (GameWindows[Win].Input.SelfPlayMode == 2)
                WriteOutRecordData(Win);
            GameWindows[Win].Input.SelfPlayMode = 0;
            Input->Padd = 0;
        }
        else
        {
            Input->Padd = Input->Original;
            *Input->SelfPlayPntr = Input->Padd & 0xfff0;
            if (Win == 0)
            {
                Manual = NewVcounts / PalNtscRate;
                if (Manual & 1)
                    *Input->SelfPlayPntr |= 8;
                if (Manual & 2)
                    *Input->SelfPlayPntr |= 1;
                if (Manual & 4)
                    *Input->SelfPlayPntr |= 2;
                if (Manual & 8)
                    *Input->SelfPlayPntr |= 4;
            }
            Input->SelfPlayPntr++;
        }
        break;
    case 3:
        Input->OPadd = Input->Padd;
        Input->Padd = 0;
        break;
    case 4:
        break;
    default:
        Input->OPadd = Input->Padd;
        break;
    }
    if (Input->Padd)
        LastInputTime = ChrisCount;
}

void SwapAllButtons(void)
{
    int Win;
    int TimeoutTime;
    for (Win = 0; Win < 4; Win++)
        SwapButtons(Win);
    if (NoInputTimeOutRoutine) {
        TimeoutTime = LastInputTime + NoInputTime;
        if (ChrisCount >= TimeoutTime)
            NoInputTimeOutRoutine();
    }
}

void WriteOutRecordData(int Win)
{
    struct CTRLER *Input;
    int Size;
    int Handle;
    int Count;
    char *NumString;
    char FileString[20];

    Input = &GameWindows[Win].Input;
    Size = Input->SelfPlayPntr - Input->SelfPlayBasePntr;
    strcpy(FileString, "c:\\SPlay");
    strcat(FileString, itoa(Win));
    strcat(FileString, ".Txt");
    Handle = PCcreat(FileString, 0);
    PCwrite(Handle, "Data for Window ", 16);
    PCwrite(Handle, itoa(Win), 1);
    PCwrite(Handle, EolString, EolLength);
    for (Count = 0; Count < Size; Count++)
    {
        NumString = itoa(Input->SelfPlayBasePntr[Count]);
        strcat(NumString, ",");
        if ((Count & 15) == 15)
            strcat(NumString, EolString);
        PCwrite(Handle, NumString, strlen(NumString));
    }
    PCwrite(Handle, "-1", 2);
    PCwrite(Handle, EolString, EolLength);
    PCclose(Handle);
    MyFreeRep((void **)&Input->SelfPlayBasePntr, "Record Stuff");
}

short SnapShotPadViolation(short winNum, char *portId)
{
    struct HHPADD *pPadd;

    pPadd = &PaddData[SnapShot[winNum].HHPadId];
    if (SnapShot[winNum].viaMTap)
    {
        if (SnapShot[winNum].viaMTap == 1)
        {
            if (!MultiTapExists[0])
            {
                *portId = 0;
                return 3;
            }
        }
        else
        {
            if (!MultiTapExists[1])
            {
                *portId = 0x10;
                return 3;
            }
        }
    }
    SnapShot[winNum].PadOk = pPadd->CType == 5 || pPadd->CType == 7 || pPadd->CType == 4;
    *portId = SnapShot[winNum].PadPortId;
    if (!SnapShot[winNum].PadOk)
        return 1;
    if (!SnapShot[winNum].MouseOk && Engine.GameConfig.MultiPlayerParams[winNum].useMouse)
    {
        if (SnapShot[winNum].viaMTapMouse)
        {
            if (SnapShot[winNum].viaMTapMouse == 1)
            {
                if (!MultiTapExists[0])
                {
                    *portId = 0;
                    return 3;
                }
            }
            else
            {
                if (!MultiTapExists[1])
                {
                    *portId = 0x10;
                    return 3;
                }
            }
        }
        *portId = SnapShot[winNum].MousePortId;
        return 2;
    }
    return 0;
}
