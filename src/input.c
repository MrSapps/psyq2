void PadDualShock(int Win, struct HHPADD *Padds)
{
    int Port;
    int PadState;
    struct CHARPAIR Shocks;

    Port = Padds->PortId;
    PadState = PadGetState(Port);
    if (!Paused && !InSelfPlayMode && Engine.GameConfig.MultiPlayerParams[Win].vibration)
    {
        Shocks = ProcessShockData(Win);
        if (Engine.GameConfig.sNumPlayers >= 3 && LevelIsMultiPlayer)
        {
            if (ChrisCount & 1)
            {
                if (!(Win & 1))
                    memset(&Shocks, 0, 2);
            }
            else
            {
                if (Win & 1)
                    memset(&Shocks, 0, 2);
            }
        }
    }
    else
        memset(&Shocks, 0, 2);

    if (PadState == 6 && PadInfoMode(Port, 2, 0))
    {
        Padds->IsShockable = 1;
        Padds->Motor[0] = Shocks.y;
        Padds->Motor[1] = Shocks.x;
        PadSetAct(Port, Padds->Motor, 2);
    }
    else
        Padds->IsShockable = 0;
    if (PadState == 1)
    {
        Padds->Send = 0;
        Padds->IsShockable = 0;
    }
    if (!Padds->Send)
    {
        PadSetAct(Port, Padds->Motor, 2);
        if (PadState == 2 || (PadState == 6 && PadSetActAlign(Port, PadAlign)))
            Padds->Send = 1;
    }
}

