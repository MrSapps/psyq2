void UpdateMallocStart(char *Old, char *New)
{
    int *currp;
    int *NewCurrP;
    int *lastp;
    int *nextp;
    currp = (int *)(Old - 28);
    lastp = (int *)currp[0];
    nextp = (int *)currp[1];
    NewCurrP = (int *)(New - 28);
    lastp[1] = (int)NewCurrP;
    nextp[0] = (int)NewCurrP;
    {
        int Backup[7];
        int a;
        int SizeIncrease;
        for (a = 0; a < 7; a++)
            Backup[a] = currp[a];
        for (a = 0; a < 7; a++)
            NewCurrP[a] = Backup[a];
        SizeIncrease = Old - New;
        NewCurrP[2] += SizeIncrease;
    }
}

void printheap(void)
{
    int *lastp;
    int gap;
    int TotalUsed;
    int TotalFree;
    TotalFree = 0;
    TotalUsed = 0;
    lastp = heapstart;
    printf("\n****** MEMORY -- BLOCKS *******\n");
    while (1) {
        TotalUsed += 7 + lastp[2];
        printf("USED  Address: %x   Used size: %x   ( %d )", lastp + 7, lastp[2], lastp[2]);
        printf("   '%s'\n", lastp + 3);
        if (!lastp[1])
            gap = (char *)heapend - (char *)lastp - (28 + lastp[2]);
        else
            gap = (char *)lastp[1] - (char *)lastp - (28 + lastp[2]);
        if (gap > 0) {
            TotalFree += gap;
            printf("FREE  Address: %x   Gap size:  %x   ( %d )\n", (char *)lastp + ((lastp[2] + 31) & ~3), gap, gap);
        }
        if (!lastp[1])
            break;
        lastp = (int *)lastp[1];
    }
    printf("TotalUsed %d, TotalFree %d, Total %d\n", TotalUsed, TotalFree, TotalUsed + TotalFree);
    printf("***********************\n\n");
}

void initMYmalloc2(void)
{
    heapstart = (int *)&pdhmallocbase;
    pdhmallocbase2 = (long)&pdhmallocbase;
    heapstart[1] = 0;
    heapstart[3] = 0;
    heapstart[2] = 0;
    heapend = (int *)((char *)__SN_GP_BASE - (_stacksize + 0x80000000));
}

unsigned long MaxMallocSize(void)
{
    MyMalloc(0x1000000, 0);
    return BiggestGap - 28;
}

void *MyMalloc(int Length, int HiFlag)
{
    unsigned long Gap;
    int *ThisP;
    int *NewP;
    int *NextP;
    int *BestP;
    int *BestNextP;
    int *LastAddr;
    int Required;
    int Size;

    BestNextP = 0;
    Required = (Length + 31) & ~3;
    BestP = 0;
    ThisP = heapstart;
    BiggestGap = 0;
    LastAddr = heapend - _stacksize / sizeof(int);
    do {
        NextP = LastAddr;
        Size = ThisP[2];
        Size += 31;
        Size &= ~3;
        if (ThisP[1])
            NextP = (int *)ThisP[1];
        Gap = (char *)NextP - (char *)ThisP - Size;
        if (BiggestGap < Gap)
            BiggestGap = Gap;
        if (Gap >= Required) {
            BestP = ThisP;
            BestNextP = NextP;
            if (!HiFlag)
                break;
        }
        ThisP = NextP;
    } while (NextP != LastAddr);
    if (BestP) {
        if (HiFlag)
            NewP = (int *)((char *)BestNextP - Required);
        else
            NewP = BestP + Size / sizeof(int);
        NewP[0] = (int)BestP;
        NewP[1] = BestP[1];
        NewP[2] = Length;
        BestP[1] = (int)NewP;
        NextP = (int *)NewP[1];
        if (NextP)
            NextP[0] = (int)NewP;
        return NewP + 7;
    }
    Gap = Length - BiggestGap;
    Gap /= 104;
    Gap = (int)Gap / 32;
    Gap *= 32;
    if (Length != 0x1000000)
        printf("\n!!!! WARNING !!!! MALLOC FAILED:  \nRequired %d; Available %d; Diff %d\n(approx. %d too many GT4s)\n",
               Length, BiggestGap, Length - BiggestGap, Gap);
    return 0;
}

