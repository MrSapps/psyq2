static void UnlinkBlock(int *p)
{
    int *currp;
    int *nextp;
    int *lastp;
    currp = p - 7; /* header pointer; lastp/nextp read through it */
    lastp = (int *)currp[0];
    nextp = (int *)currp[1];
    lastp[1] = (int)nextp;
    if (nextp)
        nextp[0] = (int)lastp;
}

