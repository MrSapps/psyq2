static void *MallocNoName(int s)
{
    void *p = MyMalloc(s, 0);
    if (p)
        ((int *)p)[-4] = 0;
    if ((unsigned)maxmalloc < (unsigned)((char *)p + s))
        maxmalloc = (int)((char *)p + s);
    return p;
}

